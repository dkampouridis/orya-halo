//! Synthetic traffic with no network access, for offline development, the web
//! app's load tests and the gateway's own benchmarks.
//!
//! Aircraft fly between real hubs at airliner speeds and report every second;
//! ships follow the main sea lanes or sit in port and report as AIS does
//! (every ten seconds under way, every three minutes moored). Everything is
//! generated from a fixed seed, so two runs produce the same fleet.

