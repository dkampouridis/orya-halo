/// xorshift64*: small, fast and good enough for scattering a fleet.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    /// Uniform in 0..1.
    fn unit(&mut self) -> f64 {
        (self.next() >> 11) as f64 / (1u64 << 53) as f64
    }

    fn range(&mut self, lo: f64, hi: f64) -> f64 {
        lo + (hi - lo) * self.unit()
    }

    fn pick(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
}

/// Initial bearing from one point to another, degrees clockwise from north.
fn bearing(lat1: f64, lon1: f64, lat2: f64, lon2: f64) -> f64 {
    let (p1, p2) = (lat1.to_radians(), lat2.to_radians());
    let dl = (lon2 - lon1).to_radians();
    let y = dl.sin() * p2.cos();
    let x = p1.cos() * p2.sin() - p1.sin() * p2.cos() * dl.cos();
    (y.atan2(x).to_degrees() + 360.0) % 360.0
}

/// Move a point `metres` along `heading`. Flat-earth step: fine for one second of flight.
fn advance(lat: &mut f64, lon: &mut f64, heading: f64, metres: f64) {
    let h = heading.to_radians();
    *lat = (*lat + metres * h.cos() / 111_195.0).clamp(-89.5, 89.5);
    *lon += metres * h.sin() / (111_195.0 * lat.to_radians().cos().max(0.01));
    if *lon > 180.0 {
        *lon -= 360.0;
    } else if *lon < -180.0 {
        *lon += 360.0;
    }
}

struct Plane {
    id: u32,
    lat: f64,
    lon: f64,
    alt_m: f64,
    speed: f64,
    heading: f64,
    destination: usize,
    category: u8,
    parked: bool,
    callsign: String,
    registration: String,
    type_code: &'static str,
}

/// Synthetic aircraft.
pub struct MockAircraft {
    planes: Vec<Plane>,
}

const AIRLINES: [&str; 12] = ["BAW", "DLH", "AFR", "KLM", "UAL", "DAL", "AAL", "UAE", "QFA", "SIA", "ANA", "RYR"];
const TYPES: [(&str, u8); 8] = [
    ("A320", aircraft_category::LARGE),
    ("B738", aircraft_category::LARGE),
    ("A359", aircraft_category::HEAVY),
    ("B77W", aircraft_category::HEAVY),
    ("E190", aircraft_category::MEDIUM),
    ("AT76", aircraft_category::MEDIUM),
    ("C172", aircraft_category::LIGHT),
    ("EC35", aircraft_category::ROTORCRAFT),
];

impl MockAircraft {
    pub fn new(count: u32) -> MockAircraft {
        let mut rng = Rng(0x9E37_79B9_7F4A_7C15);
        let planes = (0..count)
            .map(|i| {
                let from = rng.pick(HUBS.len());
                let mut to = rng.pick(HUBS.len());
                if to == from {
                    to = (to + 1) % HUBS.len();
                }
                let (type_code, category) = TYPES[rng.pick(TYPES.len())];
                let parked = rng.unit() < 0.05;
                let small = matches!(category, aircraft_category::LIGHT | aircraft_category::ROTORCRAFT);
                // Somewhere along the way, with a little scatter so routes are corridors, not lines.
                let t = if parked || small { rng.range(0.0, 0.03) } else { rng.unit() };
                let lat = HUBS[from].0 + (HUBS[to].0 - HUBS[from].0) * t + rng.range(-1.5, 1.5);
                let mut lon_span = HUBS[to].1 - HUBS[from].1;
                if lon_span > 180.0 {
                    lon_span -= 360.0;
                } else if lon_span < -180.0 {
                    lon_span += 360.0;
                }
                let mut lon = HUBS[from].1 + lon_span * t + rng.range(-1.5, 1.5);
                lon = (lon + 540.0).rem_euclid(360.0) - 180.0;
                Plane {
                    id: 0x40_0000 + i * 3,
                    lat: lat.clamp(-85.0, 85.0),
                    lon,
                    alt_m: if parked {
                        0.0
                    } else if small {
                        rng.range(300.0, 2500.0)
                    } else {
                        rng.range(8000.0, 12_500.0)
                    },
                    speed: if parked {
                        0.0
                    } else if small {
                        rng.range(40.0, 70.0)
                    } else {
                        rng.range(200.0, 260.0)
                    },
                    heading: 0.0,
                    destination: to,
                    category,
                    parked,
                    callsign: format!("{}{}", AIRLINES[rng.pick(AIRLINES.len())], 100 + rng.pick(8900)),
                    registration: format!("M-{:04X}", i & 0xFFFF),
                    type_code,
                }
            })
            .collect();
        MockAircraft { planes }
    }

    /// Advance the fleet by `dt` seconds and report every aircraft.
    /// `second` counts steps since the start; it staggers the repeat of static facts.
    pub fn step(&mut self, dt: f64, second: u64, time_ms: i64) -> Vec<Observation> {
        let mut out = Vec::with_capacity(self.planes.len());
        for (i, p) in self.planes.iter_mut().enumerate() {
            if !p.parked {
                let (dest_lat, dest_lon) = HUBS[p.destination];
                // Arrived: turn for another hub rather than land, so the fleet stays in the air.
                if haversine_km(p.lat, p.lon, dest_lat, dest_lon) < 60.0 {
                    p.destination = (p.destination + 1 + i % 7) % HUBS.len();
                }
                let (dest_lat, dest_lon) = HUBS[p.destination];
                p.heading = bearing(p.lat, p.lon, dest_lat, dest_lon);
                advance(&mut p.lat, &mut p.lon, p.heading, p.speed * dt);
            }
            // One aircraft declares an emergency for a minute, to exercise the ticker.
            let emergency = i == 7 && (20..80).contains(&(second % 600));
            let mut flags = if p.parked { flag::STATIONARY } else { 0 };
            if emergency {
                flags |= flag::EMERGENCY;
            }
            let mut obs = Observation::new(p.id);
            obs.fix = Some(Fix::from_si(
                p.lon,
                p.lat,
                p.alt_m,
                (!p.parked).then_some(p.heading),
                p.speed,
                0.0,
                flags,
                time_ms,
            ));
            obs.category = Some(p.category);
            // Facts go with the first report and then once a minute, as a real feed repeats them.
            if second == 0 || (second + i as u64).is_multiple_of(60) || i == 7 {
                obs.fact(MetaKey::Label, &p.callsign);
                obs.fact(MetaKey::Registration, &p.registration);
                obs.fact(MetaKey::TypeCode, p.type_code);
                obs.fact(MetaKey::Squawk, if emergency { "7700" } else { "2000" });
            }
            out.push(obs);
        }
        out
    }

    async fn run_loop(mut self, mut ctx: UpstreamContext) {
        ctx.state.set_status(UpstreamStatus::Ok, format!("Simulating {} aircraft.", self.planes.len()));
        let mut ticker = tokio::time::interval(Duration::from_secs(1));
        ticker.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
        let mut second = 0u64;
        loop {
            tokio::select! {
                _ = ticker.tick() => {}
                _ = ctx.shutdown.changed() => break,
            }
            let observations = self.step(1.0, second, now_ms());
            second += 1;
            ctx.push(observations).await;
        }
    }
}

impl Upstream for MockAircraft {
    fn info(&self) -> SourceInfo {
        SourceInfo {
            id: "mock-aircraft",
            name: "Simulated aircraft",
            kind: Kind::Aircraft,
            licence: MOCK_LICENCE,
            attribution: "Simulated traffic, not real aircraft",
            attribution_url: "",
            docs: "",
            requires_key: None,
            coverage: "worldwide",
        }
    }

    fn run(self: Box<Self>, ctx: UpstreamContext) -> BoxFuture {
        Box::pin(self.run_loop(ctx))
    }
}

struct Vessel {
    mmsi: u32,
    lat: f64,
    lon: f64,
    speed: f64,
    heading: f64,
    /// Index into `PORTS` the vessel is sailing towards.
    destination: usize,
    moored: bool,
    ship_type: u8,
    name: String,
    length: u32,
}

/// Synthetic ships.
pub struct MockShips {
    vessels: Vec<Vessel>,
}

const SHIP_TYPES: [u8; 6] = [
    ship_category::CARGO,
    ship_category::CARGO,
    ship_category::TANKER,
    ship_category::PASSENGER,
    ship_category::FISHING,
    ship_category::SERVICE,
];

/// Seconds between reports from a ship under way and from one in port.
const UNDER_WAY_PERIOD: u64 = 10;
const MOORED_PERIOD: u64 = 180;

impl MockShips {
    pub fn new(count: u32) -> MockShips {
        let mut rng = Rng(0xD1B5_4A32_D192_ED03);
        let vessels = (0..count)
            .map(|i| {
                let from = rng.pick(PORTS.len());
                let to = (from + 1) % PORTS.len();
                let moored = rng.unit() < 0.4;
                let t = if moored { 0.0 } else { rng.unit() };
                let spread = if moored { 0.15 } else { 1.2 };
                let lat = PORTS[from].0 + (PORTS[to].0 - PORTS[from].0) * t + rng.range(-spread, spread);
                let mut lon_span = PORTS[to].1 - PORTS[from].1;
                if lon_span > 180.0 {
                    lon_span -= 360.0;
                } else if lon_span < -180.0 {
                    lon_span += 360.0;
                }
                let lon = (PORTS[from].1 + lon_span * t + rng.range(-spread, spread) + 540.0).rem_euclid(360.0) - 180.0;
                Vessel {
                    mmsi: 200_000_000 + i * 13,
                    lat: lat.clamp(-80.0, 80.0),
                    lon,
                    speed: if moored { 0.0 } else { rng.range(4.0, 11.0) },
                    heading: rng.range(0.0, 360.0),
                    destination: to,
                    moored,
                    ship_type: SHIP_TYPES[rng.pick(SHIP_TYPES.len())],
                    name: format!("MOCK VESSEL {i}"),
                    length: 40 + rng.pick(320) as u32,
                }
            })
            .collect();
        MockShips { vessels }
    }

    /// Report the ships whose turn it is at `second`, having moved them on
    /// since their previous report.
    pub fn step(&mut self, second: u64, time_ms: i64) -> Vec<Observation> {
        let mut out = Vec::new();
        for (i, v) in self.vessels.iter_mut().enumerate() {
            let period = if v.moored { MOORED_PERIOD } else { UNDER_WAY_PERIOD };
            if second != 0 && !(second + i as u64).is_multiple_of(period) {
                continue;
            }
            if !v.moored {
                let (dest_lat, dest_lon) = PORTS[v.destination];
                if haversine_km(v.lat, v.lon, dest_lat, dest_lon) < 150.0 {
                    v.destination = (v.destination + 1) % PORTS.len();
                }
                let (dest_lat, dest_lon) = PORTS[v.destination];
                v.heading = bearing(v.lat, v.lon, dest_lat, dest_lon);
                if second != 0 {
                    advance(&mut v.lat, &mut v.lon, v.heading, v.speed * period as f64);
                }
            }
            let mut obs = Observation::new(v.mmsi);
            obs.fix = Some(Fix::from_si(
                v.lon,
                v.lat,
                0.0,
                Some(v.heading),
                v.speed,
                0.0,
                if v.moored { flag::STATIONARY } else { 0 },
                time_ms,
            ));
            // Static data repeats every six minutes, like AIS message 5.
            if second == 0 || (second + i as u64).is_multiple_of(360) {
                obs.category = Some(v.ship_type);
                obs.fact(MetaKey::Label, &v.name);
                obs.fact(MetaKey::LengthM, v.length.to_string());
                obs.fact(MetaKey::NavStatus, if v.moored { "Moored" } else { "Under way using engine" });
            }
            out.push(obs);
        }
        out
    }

    async fn run_loop(mut self, mut ctx: UpstreamContext) {
        ctx.state.set_status(UpstreamStatus::Ok, format!("Simulating {} ships.", self.vessels.len()));
        let mut ticker = tokio::time::interval(Duration::from_secs(1));
        ticker.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
        let mut second = 0u64;
        loop {
            tokio::select! {
                _ = ticker.tick() => {}
                _ = ctx.shutdown.changed() => break,
            }
            let observations = self.step(second, now_ms());
            second += 1;
            ctx.push(observations).await;
        }
    }
}

