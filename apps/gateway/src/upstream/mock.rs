#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_fleet_is_deterministic_and_plausible() {
        let mut a = MockAircraft::new(500);
        let mut b = MockAircraft::new(500);
        let first = a.step(1.0, 0, 1_000);
        assert_eq!(first, b.step(1.0, 0, 1_000));
        assert_eq!(first.len(), 500);
        let mut ids: Vec<u32> = first.iter().map(|o| o.id).collect();
        ids.dedup();
        assert_eq!(ids.len(), 500, "ids are unique");
        assert!(first.iter().all(|o| o.id <= 0xFF_FFFF && o.fix.is_some() && !o.meta.is_empty()));
        let parked = first.iter().filter(|o| o.fix.unwrap().flags & flag::STATIONARY != 0).count();
        assert!((5..80).contains(&parked), "{parked} parked");
    }

    #[test]
    fn aircraft_move_at_flying_speed() {
        let mut fleet = MockAircraft::new(200);
        let before = fleet.step(1.0, 0, 0);
        let mut after = Vec::new();
        for second in 1..=10 {
            after = fleet.step(1.0, second, second as i64 * 1000);
        }
        let mut moved = 0;
        for (a, b) in before.iter().zip(&after) {
            let (fa, fb) = (a.fix.unwrap(), b.fix.unwrap());
            let km = haversine_km(fa.lat(), fa.lon(), fb.lat(), fb.lon());
            assert!(km < 3.0, "{km} km in ten seconds is too fast");
            if km > 0.3 {
                moved += 1;
            }
        }
        assert!(moved > 150, "{moved} of 200 moved");
        // Facts are not repeated every second.
        assert!(after.iter().filter(|o| o.meta.is_empty()).count() > 150);
    }

    #[test]
    fn one_aircraft_squawks_an_emergency_for_a_while() {
        let mut fleet = MockAircraft::new(20);
        let calm = fleet.step(1.0, 5, 0);
        assert!(calm.iter().all(|o| o.fix.unwrap().flags & flag::EMERGENCY == 0));
        let alarm = fleet.step(1.0, 30, 0);
        let squawking: Vec<_> = alarm.iter().filter(|o| o.fix.unwrap().flags & flag::EMERGENCY != 0).collect();
        assert_eq!(squawking.len(), 1);
        assert!(squawking[0].meta.contains(&(MetaKey::Squawk, "7700".to_owned())));
    }

    #[test]
    fn ships_report_at_ais_cadence() {
        let mut fleet = MockShips::new(1000);
        let all = fleet.step(0, 0);
        assert_eq!(all.len(), 1000);
        assert!(all.iter().all(|o| (200_000_000..800_000_000).contains(&o.id)));
        let moored = all.iter().filter(|o| o.fix.unwrap().flags & flag::STATIONARY != 0).count();
        assert!((300..500).contains(&moored), "{moored} moored");
        // Over three minutes every ship reports at least once, and nowhere near every second.
        let mut reports = 0;
        let mut seen = std::collections::HashSet::new();
        for second in 1..=180 {
            for o in fleet.step(second, second as i64 * 1000) {
                reports += 1;
                seen.insert(o.id);
            }
        }
        assert_eq!(seen.len(), 1000);
        assert!((10_000..13_000).contains(&reports), "{reports} reports in three minutes");
    }
}
